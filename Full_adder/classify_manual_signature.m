        string(predictedClass), ...
        confidence, ...
        string(sprintf("%d", observedSum)), ...
        string(sprintf("%d", observedCout)), ...
        'VariableNames', { ...
            'PredictedFault', ...
            'Confidence', ...
            'ObservedSumSignature', ...
            'ObservedCoutSignature'});
end
